// @vitest-environment jsdom
import { beforeEach, describe, expect, test, vi } from 'vitest';

import { mountStimulusView } from '../../src/components/stimulus-view';
import type { StimulusViewProps } from '../../src/components/stimulus-view';
import { surveyFixture } from '../helpers/dom';
import type { LoadedImage } from '../../src/lib/image-loader';
import type { Trial } from '../../src/study-state';

const TRIAL = {
    id: 7,
    prompt: 'Which is the better cat?',
    method_a: 'alpha',
    method_b: 'beta',
    image_a_url: 'https://img/a.png',
    image_b_url: 'https://img/b.png',
    total_pairs: 4,
} as Trial;

const ok: LoadedImage = { ok: true };
const failed: LoadedImage = { ok: false };

export type Harness = {
    props: StimulusViewProps;
    blocked: boolean[];
    settled: boolean[];
    opened: string[];
    shown: string[];
    view: ReturnType<typeof mountStimulusView>;
    a: HTMLImageElement;
    b: HTMLImageElement;
};

function harness(
    preload: (url: string) => Promise<LoadedImage> = async () => ok,
    over: Partial<StimulusViewProps> = {},
): Harness {
    surveyFixture();
    const blocked: boolean[] = [];
    const settled: boolean[] = [];
    const opened: string[] = [];
    const shown: string[] = [];
    const props: StimulusViewProps = {
        lightbox: { open: (src) => opened.push(src), close: vi.fn(), dispose: vi.fn() },
        banner: { show: (message) => shown.push(message), hide: vi.fn(), dispose: vi.fn() },
        onBlockingChange: (value) => blocked.push(value),
        onSettled: (value) => settled.push(value),
        preload,
        ...over,
    };
    const view = mountStimulusView(document.body, props);
    return {
        props,
        blocked,
        settled,
        opened,
        shown,
        view,
        a: document.getElementById('image-a') as HTMLImageElement,
        b: document.getElementById('image-b') as HTMLImageElement,
    };
}

const indicators = () => document.querySelectorAll('.loading-indicator');

describe('StimulusView', () => {
    let h: Harness;

    beforeEach(() => {
        h = harness();
    });

    test('a load paints the loading state and blocks the form', () => {
        const pending = h.view.show(TRIAL);

        expect(h.a.style.opacity).toBe('0.3');
        // The reflected src resolves against the document base; the attribute is the honest read.
        expect(h.a.getAttribute('src')).toBe('');
        expect(h.a.alt).toBe('Loading alpha...');
        expect(h.b.alt).toBe('Loading beta...');
        expect(indicators()).toHaveLength(2);
        expect(h.blocked).toEqual([true]);
        return pending;
    });

    test('a successful load commits both tiles with their provenance', async () => {
        await h.view.show(TRIAL);

        expect(h.a.src).toBe('https://img/a.png');
        expect(h.b.src).toBe('https://img/b.png');
        expect(h.a.alt).toBe('Image generated by alpha');
        expect(h.a.dataset.method).toBe('alpha');
        expect(h.a.dataset.url).toBe('https://img/a.png');
        expect(h.a.style.opacity).toBe('1');
        expect(h.a.crossOrigin).toBe('anonymous');
        expect(indicators()).toHaveLength(0);
        expect(h.blocked).toEqual([true, false]);
        expect(h.settled).toEqual([true]);
    });

    test('the prompt belongs to the pair, not to the study', async () => {
        await h.view.show(TRIAL);
        expect(document.getElementById('prompt-text')!.textContent).toBe('Which is the better cat?');
    });

    test('a tile that fails to load names itself and unblocks the form', async () => {
        await h.view.show(TRIAL);
        h = harness((url) => Promise.resolve(url.endsWith('a.png') ? failed : ok));
        await h.view.show(TRIAL);

        expect(h.shown).toEqual(['Failed to load images: Image A. Refresh the page to try this pair again.']);
        expect(h.a.getAttribute('src')).toBe('');
        expect(h.a.style.opacity).toBe('1');
        expect(indicators()).toHaveLength(0);
        expect(h.settled).toEqual([false]);
        expect(h.blocked).toEqual([true, false]);
    });

    test('when both tiles fail the message names both', async () => {
        h = harness(async () => failed);
        await h.view.show(TRIAL);

        expect(h.shown[0]).toBe('Failed to load images: Image A Image B. Refresh the page to try this pair again.');
    });

    test('a load that never lands settles as a failure and frees the form', async () => {
        vi.useFakeTimers();
        h = harness(() => new Promise<LoadedImage>(() => {}), { loadTimeoutMs: 1000 });
        const shown = h.view.show(TRIAL);

        expect(h.blocked).toEqual([true]);
        await vi.advanceTimersByTimeAsync(1000);
        await shown;

        expect(h.blocked).toEqual([true, false]);
        expect(h.settled).toEqual([false]);
        expect(h.shown[0]).toContain('Refresh the page');
        expect(indicators()).toHaveLength(0);
        vi.useRealTimers();
    });

    test('a trial the participant could not see is marked failed, a rendered pair is not', async () => {
        expect(h.view.failed()).toBe(false);

        h = harness(async () => failed);
        await h.view.show(TRIAL);
        expect(h.view.failed()).toBe(true);

        h = harness(async () => ok);
        await h.view.show(TRIAL);
        expect(h.view.failed()).toBe(false);
    });

    test('a stalled load that is superseded does not fail the pair being judged', async () => {
        vi.useFakeTimers();
        h = harness((url) => (url.includes('slow')
            ? new Promise<LoadedImage>(() => {})
            : Promise.resolve(ok)), { loadTimeoutMs: 1000 });

        const stalled = h.view.show({ ...TRIAL, image_a_url: 'https://img/slow.png' });
        await h.view.show(TRIAL);
        await vi.advanceTimersByTimeAsync(1000);
        await stalled;

        expect(h.view.failed()).toBe(false);
        expect(h.settled).toEqual([true]);
        vi.useRealTimers();
    });

    test('a committed tile opens the lightbox, a loading one does not', async () => {
        h.a.click();
        expect(h.opened).toEqual([]);

        await h.view.show(TRIAL);
        h.a.click();
        h.b.click();
        expect(h.opened).toEqual(['https://img/a.png', 'https://img/b.png']);
    });

    test('a superseded pair never paints over the pair being judged', async () => {
        let slowA: ((value: LoadedImage) => void) | null = null;
        h = harness((url) => {
            if (url.includes('slow')) return new Promise<LoadedImage>((resolve) => { slowA = resolve; });
            return Promise.resolve(ok);
        });

        const first = h.view.show({ ...TRIAL, image_a_url: 'https://img/slow.png' });
        await h.view.show({ ...TRIAL, image_a_url: 'https://img/next.png' });
        expect(h.a.src).toBe('https://img/next.png');

        slowA!(ok);
        await first;

        expect(h.a.src).toBe('https://img/next.png');
        expect(h.settled).toEqual([true]);
    });

    test('dispose unbinds the tiles', async () => {
        await h.view.show(TRIAL);
        h.view.dispose();
        h.a.click();
        expect(h.opened).toEqual([]);
    });
});
